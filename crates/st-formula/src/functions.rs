//! The function catalogue the formula builder lists, from
//! `GET /api/database/formula/functions/` (`src/routes/database/formula.ts`).

use serde::Serialize;

/// A function as the formula builder shows it.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
pub struct FunctionInfo {
    pub name: &'static str,
    pub signature: &'static str,
    /// `logic`, `text`, `number`, `date`, `array`, `link` or `file`.
    pub category: &'static str,
}

const fn info(name: &'static str, signature: &'static str, category: &'static str) -> FunctionInfo {
    FunctionInfo {
        name,
        signature,
        category,
    }
}

